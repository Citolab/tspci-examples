export const textsFor = (language: unknown): Texts => (String(language ?? "").toLowerCase().startsWith("nl") ? nl : en);

/** A number as the language writes it (a decimal comma in Dutch). */
export const formatNumber = (t: Texts, n: number, decimals = 1) => n.toLocaleString(t.locale === "nl" ? "nl-NL" : "en-GB", { maximumFractionDigits: decimals });
