export const textsFor = (language: string | undefined): Texts => ((language ?? "").toLowerCase().startsWith("nl") ? nl : en);

/** The name of a dimension: "Slot: depth", "Width". */
export const dimLabel = (t: Texts, dim: Dim, features: Feature[]) => {
  const f = features[dim.feature];
  const type = f?.type ?? "block";
  const key = t.dimKey[`${type}.${dim.key}`] ?? dim.key;
  if (type === "block") return key;
  const same = features.filter((g) => g.type === type);
  const n = same.length > 1 ? ` ${same.indexOf(f) + 1}` : "";
  return `${t.feature[type]}${n}: ${key}`;
};
