import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import type { Plugin } from "vite";

/**
 * Builds the source of a PCI the way tspci's rollup build does (node_modules/@citolab/tspci/src/rollup.config.js), so
 * a story runs the same code as the bundle:
 * - `qtiCustomInteractionContext` is the delivery system's module: here a stand-in that registers nothing;
 * - `import style from "./style.css"` is the CSS as a string, through the PCI's own PostCSS/Tailwind, with tspci's fix
 *   for `@property` in a shadow root;
 * - `import config from "./config.json"` is the plain defaults, without the editor hints;
 * - `import image from "./image.svg"` is a data: URL (@rollup/plugin-image);
 * - `import { slot, media } from "@citolab/tspci/media"` is tspci's runtime, with the fixed media served by Vite;
 * - react is preact/compat.
 * Only files of a PCI (tspci-* /src, tspci-* /node_modules) are touched, never Storybook's own.
 */

const CONTEXT = "\0tspci:qtiCustomInteractionContext";
const CSS_PREFIX = "\0tspci-css:";
const MEDIA_PREFIX = "\0tspci-media:";
const CSS_SUFFIX = ".js"; // so Vite's CSS plugin leaves the module alone
const IMAGE_TYPES: Record<string, string> = {
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
};
const REACT_ALIASES: Record<string, string> = {
  react: "preact/compat",
  "react-dom": "preact/compat",
  "react-dom/test-utils": "preact/test-utils",
  "react/jsx-runtime": "preact/jsx-runtime",
};

const clean = (id: string) => id.split("?")[0];

/** A path with forward slashes, as Vite writes module ids also on Windows. */
const posix = (file: string) => file.replace(/\\/g, "/");

/** Whether a file is in a folder named src (with either separator: Vite's ids or Node's paths). */
const inSrc = (file: string) => /[\\/]src[\\/]/.test(clean(file));

/** The folder of the PCI a file belongs to (tspci-table-graph), or undefined for any other file. */
const pciRoot = (file: string): string | undefined => {
  const match = /^(.*[\\/]tspci-[^\\/]+)[\\/](src|node_modules)[\\/]/.exec(clean(file));
  return match && fs.existsSync(path.join(match[1], "package.json")) ? match[1] : undefined;
};

/** A module of the tspci version the PCI builds with. */
const tspciModule = (root: string, file: string) =>
  import(pathToFileURL(path.join(root, "node_modules/@citolab/tspci/src", file)).href);

/** The PostCSS plugins of the PCI's postcss.config.js, with Tailwind scanning the PCI's folder (as `tspci` run there). */
const postcssPlugins = (root: string) => {
  if (!fs.existsSync(path.join(root, "postcss.config.js"))) return [];
  const require = createRequire(path.join(root, "package.json"));
  return [require("@tailwindcss/postcss")({ base: root }), require("autoprefixer")];
};

/** react → preact/compat for a PCI's dependencies, also where Vite pre-bundles them (@react-hook/mouse-position). */
const reactToPreact = {
  name: "tspci-react-to-preact",
  resolveId(this: { resolve: Function }, source: string, importer?: string) {
    if (!importer || !pciRoot(importer) || !REACT_ALIASES[source]) return null;
    return this.resolve(REACT_ALIASES[source], importer, { skipSelf: true });
  },
};

export function tspci(): Plugin {
  return {
    name: "tspci",
    enforce: "pre",

    config: () => ({
      // one preact for all examples (the root's, the version they all build with), as rollup's dedupe in a build
      resolve: { dedupe: ["preact"] },
      optimizeDeps: {
        // the examples use different versions of three (3d-blocks 0.136, the others 0.180), and the optimizer keeps one
        // per name: leave it to each example's own node_modules (it is ES modules already)
        exclude: ["three"],
        // merged into the config: added to the optimizer's own plugins
        rolldownOptions: { plugins: [reactToPreact] },
      },
    }),

    async resolveId(source, importer) {
      if (!importer || !pciRoot(importer)) return null;
      if (source === "qtiCustomInteractionContext") return CONTEXT;
      // generated by tspci's build: here from the PCI's own tspci runtime, its fixed media served by Vite
      if (source === "@citolab/tspci/media") return MEDIA_PREFIX + pciRoot(importer);
      if (REACT_ALIASES[source]) return reactToPreact.resolveId.call(this, source, importer);
      if (clean(source).endsWith(".css") && inSrc(importer)) {
        const resolved = await this.resolve(source, importer, { skipSelf: true });
        if (resolved) return CSS_PREFIX + clean(resolved.id) + CSS_SUFFIX;
      }
      return null;
    },

    async load(id) {
      if (id === CONTEXT) {
        // The PCI registers itself when its module loads; the stories create their own instances (.storybook/tspci.ts)
        return "export const register = () => {};";
      }
      if (id.startsWith(MEDIA_PREFIX)) {
        const root = id.slice(MEDIA_PREFIX.length);
        const runtime = posix(path.join(root, "node_modules/@citolab/tspci/src/media-runtime.js"));
        const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
        // every fixed media file by URL, as a build puts a small one in the bundle (config.tspci.media)
        const table = Object.fromEntries(
          Object.entries<string | { file: string }>(pkg.config?.tspci?.media ?? {}).map(([name, entry]) => [
            name,
            // /@fs/Users/... on macOS and Linux, /@fs/C:/Users/... on Windows
            { inline: `/@fs/${posix(path.resolve(root, typeof entry === "string" ? entry : entry.file)).replace(/^\//, "")}` },
          ]),
        );
        const options = { key: `${pkg.config?.tspci?.typeIdentifier}@${pkg.version}`, typeIdentifier: pkg.config?.tspci?.typeIdentifier };
        return [
          `import { createMedia } from ${JSON.stringify(runtime)};`,
          `export { slot, SLOT_ATTRIBUTE, MEDIA_ATTRIBUTE } from ${JSON.stringify(runtime)};`,
          `export const media = createMedia(${JSON.stringify(table)}, ${JSON.stringify(options)});`,
        ].join("\n");
      }
      if (id.startsWith(CSS_PREFIX)) {
        const file = id.slice(CSS_PREFIX.length, -CSS_SUFFIX.length);
        const root = pciRoot(file)!;
        this.addWatchFile(file);
        const { default: postcss } = await import("postcss");
        const result = await postcss(postcssPlugins(root)).process(fs.readFileSync(file, "utf8"), { from: file, map: false });
        for (const message of result.messages) {
          if (message.type === "dependency") this.addWatchFile(message.file);
        }
        const { shadowRootPropertyDefaults } = await tspciModule(root, "rollup-plugin-postcss-string.js");
        return `export default ${JSON.stringify(shadowRootPropertyDefaults(result.root).toString())};`;
      }
      const file = clean(id);
      const type = IMAGE_TYPES[path.extname(file).toLowerCase()];
      if (type && pciRoot(file) && inSrc(file)) {
        const data = fs.readFileSync(file).toString("base64");
        return `export default ${JSON.stringify(`data:${type};base64,${data}`)};`;
      }
      return null;
    },

    async transform(code, id) {
      const file = clean(id);
      const root = pciRoot(file);
      if (!root || posix(file) !== posix(path.join(root, "src", "config.json"))) return null;
      const { flattenConfig } = await tspciModule(root, "authoring.js");
      return { code: JSON.stringify(flattenConfig(JSON.parse(code))), map: null };
    },
  };
}
