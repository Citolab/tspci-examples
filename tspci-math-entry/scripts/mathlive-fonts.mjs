// Writes src/mathlive-fonts.generated.ts: the @font-face rules of MathLive's KaTeX fonts (MIT, in node_modules/mathlive)
// with the fonts inlined as data: URLs. The PCI is one AMD file, so it cannot load the fonts from a directory next to it.
import fs from "fs";
import path from "path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const fontsDir = path.join(root, "node_modules", "mathlive", "fonts");
const css = fs.readFileSync(path.join(root, "node_modules", "mathlive", "mathlive-fonts.css"), "utf-8");

const inlined = css
  .replace(/^\/\*.*?\*\//, "")
  .replace(/url\(fonts\/([\w-]+\.woff2)\)/g, (_, file) =>
    `url(data:font/woff2;base64,${fs.readFileSync(path.join(fontsDir, file)).toString("base64")})`);

const target = path.join(root, "src", "mathlive-fonts.generated.ts");
const source = `// Generated by scripts/mathlive-fonts.mjs from mathlive/mathlive-fonts.css (MIT): do not edit.\nconst fonts: string = ${JSON.stringify(inlined)};\nexport default fonts;\n`;
if (!fs.existsSync(target) || fs.readFileSync(target, "utf-8") !== source) fs.writeFileSync(target, source);
