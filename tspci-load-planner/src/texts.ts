/** 12.5 → "12.5" or "12,5". */
export const formatNumber = (n: number, language: string, digits = 0) =>
  new Intl.NumberFormat(language.startsWith("nl") ? "nl-NL" : "en-GB", { maximumFractionDigits: digits, minimumFractionDigits: 0 }).format(
    Math.abs(n) < 0.5 * 10 ** -digits ? 0 : n
  );

