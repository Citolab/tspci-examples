export const languageOf = (value: unknown): "en" | "nl" => (String(value ?? "").slice(0, 2).toLowerCase() === "nl" ? "nl" : "en");
export const textsFor = (language: unknown): Texts => (languageOf(language) === "nl" ? nl : en);
/** Numbers in the author's fields: a decimal comma in Dutch. */
export const formatNumber = (n: number, language: string) => {
  const s = String(Math.round(n * 1000) / 1000);
  return languageOf(language) === "nl" ? s.replace(".", ",") : s;
};
