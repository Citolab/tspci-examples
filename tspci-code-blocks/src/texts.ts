/** "nl", "nl-NL", "fr" … → its texts; anything else English. */
export const textsFor = (language: string | undefined): Texts => TEXTS[(language ?? "").slice(0, 2).toLowerCase()] ?? en;

/** An error of a run in plain language: "Error on line 3: the variable x has no value yet." */
export const errorMessage = (t: Texts, error: RunError): string => {
  const explain = t.errors[error.code] ?? t.errors.syntax;
  const text = explain(error.detail);
  if (error.code === "empty") return text;
  return `${t.errorOn(error.line)} ${text}`;
};

